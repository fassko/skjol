// Regenerates lib/abi/*.ts from Foundry build output (run after `forge build`).
import { readFileSync, writeFileSync } from "node:fs";
const items = [
  ["ShipmentDelayPool", "contracts/out/ShipmentDelayPool.sol/ShipmentDelayPool.json", "poolAbi"],
  ["MockUSDC", "contracts/out/MockUSDC.sol/MockUSDC.json", "mockUsdcAbi"],
  ["LocalReportRelay", "contracts/out/LocalReportRelay.sol/LocalReportRelay.json", "localRelayAbi"],
];
for (const [name, file, exportName] of items) {
  const j = JSON.parse(readFileSync(file, "utf8"));
  const body = `// Generated by scripts/export-abi.mjs from ${file}. Do not edit.\nexport const ${exportName} = ${JSON.stringify(j.abi, null, 2)} as const;\n\nexport const ${exportName.replace("Abi", "Bytecode")} = ${JSON.stringify(j.bytecode.object)} as \`0x\${string}\`;\n`;
  writeFileSync(`lib/abi/${name}.ts`, body);
  console.log("wrote", `lib/abi/${name}.ts`, j.abi.length, "entries");
}
